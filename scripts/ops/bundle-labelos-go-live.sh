#!/usr/bin/env bash
#
# Build supabase/apply/labelos-go-live.sql — ONE paste for the production
# Supabase SQL editor that takes a database from "001-129 applied" to
# "BStudio Label OS fully applied":
#
#   scripts/ops/bundle-labelos-go-live.sh > supabase/apply/labelos-go-live.sql
#
# Order (the file order is the apply order):
#   0. a guard: creator_profiles must hold EXACTLY ONE row (the producer);
#   a. every migration numbered 130 or above, in number order: main's
#      still-pending 130-135 and 139_buyer_offer_email_verified, and every Label
#      OS one (136-173, 189-192 today). 139_labelos_org_contacts shares its
#      number with the buyer 139 and sorts after it; the two are independent
#      (see supabase/MIGRATIONS.md);
#   c. the platform-operator row for the producer, chosen by creator_profiles;
#   d. the verify SELECT (supabase/apply/labelos-verify.sql), one row each.
#
# All of it runs in ONE transaction: an error rolls everything back and the
# database is exactly as it was. Every migration is idempotent, so running the
# whole file again after fixing the cause (or after a success) is safe.
#
# The SQL editor does not keep one session across a script, so a migration that
# reads its own TEMP table in a later statement needs the same-effect form in
# supabase/apply/editor/<same name>, which is used instead. This script refuses
# a migration that uses a TEMP table, psql meta-commands, CONCURRENTLY, or its
# own BEGIN/COMMIT without one.

set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
MIG="$ROOT/supabase/migrations"
EDITOR_DIR="$ROOT/supabase/apply/editor"

# Every migration numbered 130 or above: main's still-pending 130-135 and
# 139_buyer_offer_email_verified, then every Label OS one (136-172, 173, 189-192
# today, including 191_portal_contact_uploads, which has no labelos_ prefix).
# Number order; at the shared 139, buyer sorts before labelos. Nothing from
# an open PR is on the branch, so nothing from one is in here.
files=()
shopt -s nullglob
while IFS= read -r f; do
  n=$((10#$(basename "$f" | cut -c1-3)))
  [ "$n" -ge 130 ] && files+=("$f")
done < <(ls "$MIG"/*.sql | sort)

# Every file must exist, and every migration in the bundle needs its row in the
# verify table (supabase/apply/labelos-verify.sql), so a migration merged later
# cannot ride along unchecked: add its row, then rebuild.
for f in "${files[@]}"; do
  [ -f "$f" ] || { echo "missing migration file: $f" >&2; exit 1; }
  base="$(basename "$f" .sql)"
  case "$base" in 13[0-5]_*) continue ;; esac   # main's 130-135: covered by verify.sql's rows
  grep -q "('$base'" "$ROOT/supabase/apply/labelos-verify.sql" \
    || { echo "no verify row for $base: add one to supabase/apply/labelos-verify.sql" >&2; exit 1; }
done

echo "-- Generated by scripts/ops/bundle-labelos-go-live.sh on $(date -u +%Y-%m-%d)."
echo "-- BStudio Label OS go-live: paste ALL of it into Supabase → SQL editor and press Run"
echo "-- with NOTHING selected (the editor runs only the highlighted text)."
echo "-- One transaction: an error rolls everything back. Everything is idempotent —"
echo "-- fix the cause, then run the whole file again."
echo
echo "BEGIN;"
cat <<'SQL'

-- ═════════════ guard: exactly one producer ═════════════
-- A creator_profiles row IS the producer (src/proxy.ts, requireProducer). Before
-- migration 117 (26 Sep) any signed-in buyer could insert one, so check before
-- anything below treats every such row as a producer and an operator.
DO $guard$
DECLARE n integer;
BEGIN
  SELECT count(*) INTO n FROM public.creator_profiles;
  IF n <> 1 THEN
    RAISE EXCEPTION 'go-live stopped, nothing was changed: creator_profiles has % rows, expected exactly 1 (the producer). Run: SELECT user_id, display_name, created_at FROM public.creator_profiles;', n;
  END IF;
END
$guard$;
SQL

for f in "${files[@]}"; do
  base="$(basename "$f")"
  editor="$EDITOR_DIR/$base"
  if [ -f "$editor" ]; then
    src="$editor"
  else
    src="$f"
    if grep -qiE 'create (global |local )?temp(orary)? table' "$f"; then
      echo "$base uses a TEMP table; add supabase/apply/editor/$base" >&2; exit 1
    fi
    if grep -qE '^\s*\\[a-zA-Z!]' "$f"; then
      echo "$base has a psql meta-command" >&2; exit 1
    fi
    if grep -qiE 'concurrently' <(grep -vE '^\s*--' "$f"); then
      echo "$base uses CONCURRENTLY (cannot run in a transaction)" >&2; exit 1
    fi
    if grep -qiE '^\s*(begin|commit|rollback)\s*;' "$f"; then
      echo "$base has its own transaction control" >&2; exit 1
    fi
  fi
  echo
  echo "-- ═════════════ $base$([ "$src" = "$editor" ] && echo ' (SQL-editor form)') ═════════════"
  cat "$src"
  echo
done

cat <<'SQL'

-- ═════════════ platform operator: the producer ═════════════
-- Chosen by the creator_profiles row, never by a typed email. The guard above
-- has already proved there is exactly one.
INSERT INTO public.platform_admins (user_id, note)
SELECT user_id, 'owner (producer)' FROM public.creator_profiles
ON CONFLICT DO NOTHING;

COMMIT;

SQL
echo "-- ═════════════ check: every row must read 'applied' ═════════════"
cat "$ROOT/supabase/apply/labelos-verify.sql"
