#!/usr/bin/env node
// Prints ONE idempotent SQL script for the Supabase SQL editor that creates the
// Label OS test accounts (see test-accounts-model.mjs for the cast).
//
//   node scripts/ops/seed-test-accounts.mjs --password '<one password for all>' > scripts/ops/out/test-accounts.sql
//   node scripts/ops/seed-test-accounts.mjs --passwords ~/secrets/test-accounts.json > scripts/ops/out/test-accounts.sql
//
//   --password <pw>      one password for every account
//   --passwords <file>   JSON object { "<tag>": "<pw>", "default": "<pw>" }; a tag is the part after
//                        the "+" in the email (owner, admin, ar, arlimited, artist1 …). "default" is the
//                        fallback for tags not listed. Keep the file OUTSIDE the repository.
//   --email-base <addr>  plus-address base, default philipmadupro@gmail.com
//
// The generated SQL CONTAINS the passwords (the database hashes them with
// pgcrypto) — treat it as a secret: it is written under scripts/ops/out/, which is
// gitignored, and the Supabase SQL editor keeps query history. Rotate afterwards.
// Nothing here connects to any database; it only prints text.
//
// What the SQL does, all in one transaction, and only to rows it marks:
//  * creates confirmed email+password users (auth.users + auth.identities), marked with
//    raw_user_meta_data.seed = 'bstudio-test-accounts'. An address that already belongs to an
//    unmarked user ABORTS the script — an existing account is never touched or adopted.
//  * creates the two orgs through labelos_setup_org (the app's own setup function), adds the label's
//    roster artists, and brings every member in through labelos_audit_invitation_create +
//    labelos_accept_invitation, so events, scopes and seat rules are the app's own.
//  * ends with a read-only SELECT listing each test email, org, role, functions and scope.
// Re-running it is safe: existing marked users get their password reset, existing memberships are kept.

import { readFileSync } from 'node:fs';
import {
  ACCOUNTS,
  DEFAULT_EMAIL_BASE,
  ORGS,
  ROSTER,
  SEED_MARKER,
  emailFor,
  parseArgs,
  sqlLit,
  sqlTextArray,
} from './test-accounts-model.mjs';

const MIN_PASSWORD = 10;

export function resolvePasswords(args) {
  let map = {};
  if (args.passwords) {
    let parsed;
    try {
      parsed = JSON.parse(readFileSync(String(args.passwords), 'utf8'));
    } catch (err) {
      throw new Error(`cannot read --passwords file: ${err.message}`);
    }
    if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
      throw new Error('--passwords file must hold a JSON object');
    }
    map = parsed;
  }
  const shared = typeof args.password === 'string' ? args.password : map.default;
  const out = {};
  for (const a of ACCOUNTS) {
    const pw = map[a.tag] ?? shared;
    if (typeof pw !== 'string' || pw.length === 0) {
      throw new Error(`no password for "${a.tag}": pass --password, or a --passwords file with "${a.tag}" or "default"`);
    }
    if (pw.length < MIN_PASSWORD) throw new Error(`password for "${a.tag}" is shorter than ${MIN_PASSWORD} characters`);
    out[a.tag] = pw;
  }
  return out;
}

export function buildSeedSql({ emailBase, passwords }) {
  const email = (tag) => emailFor(emailBase, tag);
  const userRows = ACCOUNTS.map((a) => `    (${sqlLit(a.tag)}, ${sqlLit(email(a.tag))}, ${sqlLit(passwords[a.tag])})`).join(',\n');
  const rosterRows = ROSTER.map((r) => `    (${sqlLit(r.tag)}, ${sqlLit(r.name)}, ${sqlLit(email(r.tag))})`).join(',\n');
  const memberAccounts = ACCOUNTS.filter((a) => a.org && a.role !== 'owner');
  const memberRows = memberAccounts
    .map((a) => `    (${sqlLit(a.tag)}, ${sqlLit(a.org)}, ${sqlLit(a.role)}, ${sqlTextArray(a.functions)}, ${sqlTextArray(a.artists)})`)
    .join(',\n');
  const orgRows = Object.entries(ORGS)
    .map(([key, o]) => `    (${sqlLit(key)}, ${sqlLit(o.slug)}, ${sqlLit(o.name)}, ${sqlLit(o.kind)}, ${sqlLit(o.owner)})`)
    .join(',\n');
  const marker = sqlLit(SEED_MARKER);

  return `-- Label OS test accounts — generated by scripts/ops/seed-test-accounts.mjs
-- Paste into the Supabase SQL editor with nothing selected. Idempotent.
-- THIS FILE CONTAINS PASSWORDS: do not commit or share it.
-- Marker on every user: raw_user_meta_data.seed = ${SEED_MARKER}.
-- Remove everything it makes with scripts/ops/remove-test-accounts.mjs.

DO $seed$
DECLARE
  r        record;
  v_id     uuid;
  v_seed   text;
  v_ids    jsonb := '{}'::jsonb;   -- tag -> user id
  v_orgs   jsonb := '{}'::jsonb;   -- org key -> org id
  v_org    uuid;
  v_by     uuid;
  v_res    jsonb;
  v_contact uuid;
  v_scope  uuid[];
  v_tag    text;
  v_hash   text;
  v_new_users int := 0;
  v_new_members int := 0;
BEGIN
  -- Supabase keeps pgcrypto in the "extensions" schema; local Postgres keeps it in public.
  PERFORM set_config('search_path', 'public, extensions, auth, pg_catalog', true);

  -- 1. Users: confirmed email + password, provider 'email'. Never an unmarked existing user.
  FOR r IN SELECT * FROM (VALUES
${userRows}
  ) AS t(tag, email, pw) LOOP
    v_id := NULL; v_seed := NULL;
    SELECT u.id, u.raw_user_meta_data ->> 'seed' INTO v_id, v_seed FROM auth.users u WHERE lower(u.email) = r.email;
    IF v_id IS NOT NULL AND v_seed IS DISTINCT FROM ${marker} THEN
      RAISE EXCEPTION 'refusing: % already exists and is not a test account; nothing was changed', r.email;
    END IF;
    IF v_id IS NULL THEN
      v_id := gen_random_uuid();
      INSERT INTO auth.users (
        instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
        raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
        confirmation_token, email_change, email_change_token_new, recovery_token
      ) VALUES (
        '00000000-0000-0000-0000-000000000000', v_id, 'authenticated', 'authenticated', r.email,
        crypt(r.pw, gen_salt('bf')), now(),
        '{"provider":"email","providers":["email"]}'::jsonb,
        jsonb_build_object('seed', ${marker}, 'test_account', true, 'tag', r.tag),
        now(), now(), '', '', '', ''
      );
      v_new_users := v_new_users + 1;
    ELSE
      UPDATE auth.users SET encrypted_password = crypt(r.pw, gen_salt('bf')),
             email_confirmed_at = coalesce(email_confirmed_at, now()), updated_at = now()
       WHERE id = v_id;
    END IF;
    INSERT INTO auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
    SELECT gen_random_uuid(), v_id, v_id::text,
           jsonb_build_object('sub', v_id::text, 'email', r.email, 'email_verified', true, 'phone_verified', false),
           'email', now(), now(), now()
    WHERE NOT EXISTS (SELECT 1 FROM auth.identities i WHERE i.user_id = v_id AND i.provider = 'email');
    v_ids := v_ids || jsonb_build_object(r.tag, v_id);
  END LOOP;

  -- 2. Organizations, through the app's setup function (owner + org in one transaction).
  FOR r IN SELECT * FROM (VALUES
${orgRows}
  ) AS t(key, slug, name, kind, owner_tag) LOOP
    SELECT o.id, o.created_by INTO v_org, v_by FROM public.organizations o WHERE o.slug = r.slug;
    IF v_org IS NOT NULL THEN
      IF v_by IS DISTINCT FROM (v_ids ->> r.owner_tag)::uuid THEN
        RAISE EXCEPTION 'refusing: slug % belongs to an organization this script did not create', r.slug;
      END IF;
    ELSE
      v_res := public.labelos_setup_org((v_ids ->> r.owner_tag)::uuid, r.kind, r.name, '{}'::jsonb);
      IF coalesce(v_res ->> 'created', 'false') <> 'true' THEN
        RAISE EXCEPTION 'refusing: % already owns another organization (%)', r.owner_tag, v_res;
      END IF;
      v_org := (v_res ->> 'org_id')::uuid;
      IF v_res ->> 'slug' <> r.slug THEN
        UPDATE public.organizations SET slug = r.slug WHERE id = v_org;
      END IF;
      -- Migration 197 writes org.created inside labelos_setup_org; before it, nothing does. Only add it when absent,
      -- so the seed is right whether it is pasted before or after 197.
      IF NOT EXISTS (SELECT 1 FROM public.activity_events WHERE org_id = v_org AND verb = 'org.created') THEN
        PERFORM public.labelos_audit_insert(v_org, (v_ids ->> r.owner_tag)::uuid, 'org.created', 'org', v_org,
          jsonb_build_object('kind', r.kind, 'source', 'seed-test-accounts', 'settings', '[]'::jsonb));
      END IF;
    END IF;
    v_orgs := v_orgs || jsonb_build_object(r.key, v_org);
  END LOOP;

  -- 3. The label's roster artists (org contacts, artist role). The solo org's one artist is made by 139's trigger.
  FOR r IN SELECT * FROM (VALUES
${rosterRows}
  ) AS t(tag, name, email) LOOP
    INSERT INTO public.contacts (org_id, user_id, name, email, category)
    SELECT (v_orgs ->> 'label')::uuid, NULL, r.name, r.email, 'artist'
    WHERE NOT EXISTS (SELECT 1 FROM public.contacts c WHERE c.org_id = (v_orgs ->> 'label')::uuid AND lower(c.email) = r.email);
  END LOOP;

  -- 4. Members, through invitation create + accept (events, scope rows and seat rules are the app's own).
  FOR r IN SELECT * FROM (VALUES
${memberRows}
  ) AS t(tag, org_key, role, fns, artist_tags) LOOP
    v_org := (v_orgs ->> r.org_key)::uuid;
    v_id := (v_ids ->> r.tag)::uuid;
    CONTINUE WHEN EXISTS (SELECT 1 FROM public.org_members m WHERE m.org_id = v_org AND m.user_id = v_id);

    v_scope := '{}';
    FOREACH v_tag IN ARRAY r.artist_tags LOOP
      SELECT c.id INTO v_contact FROM public.contacts c
       WHERE c.org_id = v_org AND lower(c.email) = (SELECT t.email FROM (VALUES
${ROSTER.map((x) => `         (${sqlLit(x.tag)}, ${sqlLit(email(x.tag))})`).join(',\n')}
       ) AS t(tag, email) WHERE t.tag = v_tag);
      v_scope := v_scope || v_contact;
    END LOOP;

    v_hash := encode(digest(gen_random_uuid()::text || clock_timestamp()::text || r.tag, 'sha256'), 'hex');
    v_res := public.labelos_audit_invitation_create(
      v_org, (v_ids ->> 'owner')::uuid, (SELECT u.email FROM auth.users u WHERE u.id = v_id),
      r.role, r.fns, v_scope, v_hash, now() + interval '1 day',
      jsonb_build_object('role', r.role, 'functions', to_jsonb(r.fns), 'contact_ids', to_jsonb(v_scope), 'source', 'seed-test-accounts'));
    IF v_res ? 'error' THEN RAISE EXCEPTION 'invitation for % failed: %', r.tag, v_res; END IF;
    v_res := public.labelos_accept_invitation(v_hash, v_id);
    IF v_res ? 'error' OR v_res ->> 'status' IS DISTINCT FROM 'joined' THEN
      RAISE EXCEPTION 'accepting the invitation for % failed: %', r.tag, v_res;
    END IF;
    v_new_members := v_new_members + 1;
  END LOOP;

  RAISE NOTICE 'test accounts: % new users, % new memberships', v_new_users, v_new_members;
END
$seed$;

-- Read-only: every test account, its organization, role, functions and scope.
SELECT u.email,
       coalesce(o.slug, '(no organization)') AS org,
       coalesce(o.kind, '') AS org_kind,
       coalesce(m.role, '') AS role,
       coalesce(array_to_string(m.functions, ', '), '') AS functions,
       coalesce(m.scope, '') AS scope,
       coalesce((SELECT string_agg(c.name, ', ' ORDER BY c.name)
                   FROM public.member_artist_scopes s JOIN public.contacts c ON c.id = s.contact_id
                  WHERE s.org_id = m.org_id AND s.user_id = m.user_id), '') AS scoped_artists
  FROM auth.users u
  LEFT JOIN public.org_members m ON m.user_id = u.id
  LEFT JOIN public.organizations o ON o.id = m.org_id
 WHERE u.raw_user_meta_data ->> 'seed' = ${marker}
 ORDER BY o.slug NULLS LAST,
          CASE m.role WHEN 'owner' THEN 0 WHEN 'admin' THEN 1 WHEN 'member' THEN 2 WHEN 'artist' THEN 3 ELSE 4 END,
          u.email;
`;
}

const isMain = process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href;
if (isMain) {
  try {
    const args = parseArgs(process.argv.slice(2));
    const emailBase = typeof args['email-base'] === 'string' ? args['email-base'] : DEFAULT_EMAIL_BASE;
    process.stdout.write(buildSeedSql({ emailBase, passwords: resolvePasswords(args) }));
  } catch (err) {
    process.stderr.write(`seed-test-accounts: ${err.message}\n`);
    process.exit(1);
  }
}
