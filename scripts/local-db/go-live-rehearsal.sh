#!/usr/bin/env bash
#
# Rehearse the Label OS go-live on a THROWAWAY local Postgres — never Supabase.
#
#   scripts/local-db/go-live-rehearsal.sh        # start, rehearse, delete
#   KEEP_LOCAL_DB=1 scripts/local-db/go-live-rehearsal.sh
#
# 1. builds the PRODUCTION state: bootstrap + migrations 001-129 + a seeded
#    producer with tracks, store listings, a project, contacts, shares and a
#    buyer purchase (seed-production-state.sql);
# 2. proves the guard: a second (or no) creator_profiles row stops the bundle
#    before it changes anything;
# 3. runs supabase/apply/labelos-go-live.sql, then runs it AGAIN (idempotent),
#    and requires every verify row to read 'applied';
# 4. fingerprints every pre-existing table + auth.users before and after: no
#    existing row may change. The only expected additions are the new tables,
#    among them the producer's own org (137), its owner membership, one
#    org.created event and the platform-operator row;
# 5. runs supabase/local/checks/*.sql against copies of the migrated database
#    and the capability parity check.
#
# Needs a Postgres server install (initdb, pg_ctl, psql) and Node, like
# check.sh. Run as root, the server runs as the `postgres` OS user.

set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
PORT="${LOCAL_DB_PORT:-55433}"
BUNDLE="$ROOT/supabase/apply/labelos-go-live.sql"
PRODUCER=0b0e1a57-0000-4000-8000-000000000001

find_bin() {
  if command -v "$1" >/dev/null 2>&1; then command -v "$1"; return; fi
  local found
  found="$(ls -d /usr/lib/postgresql/*/bin/"$1" 2>/dev/null | sort -V | tail -1 || true)"
  if [ -n "$found" ]; then echo "$found"; return; fi
  echo "go-live-rehearsal: '$1' not found — install a Postgres server" >&2; exit 1
}
INITDB="$(find_bin initdb)"; PG_CTL="$(find_bin pg_ctl)"; PSQL="$(find_bin psql)"
export PATH="$(dirname "$PSQL"):$PATH"

WORK="$(mktemp -d "${LOCAL_DB_TMP:-/tmp}/golive-rehearsal.XXXXXX")"
DATA="$WORK/data"
as_server() { if [ "$(id -u)" = 0 ]; then su postgres -s /bin/sh -c "$*"; else sh -c "$*"; fi; }
if [ "$(id -u)" = 0 ]; then chown postgres "$WORK"; chmod 755 "$WORK"; fi
cleanup() {
  if [ "${KEEP_LOCAL_DB:-}" = 1 ]; then echo "kept: psql -h 127.0.0.1 -p $PORT -U postgres ($WORK)"; return; fi
  as_server "'$PG_CTL' -D '$DATA' -m immediate stop" >/dev/null 2>&1 || true
  rm -rf "$WORK"
}
trap cleanup EXIT
as_server "'$INITDB' -D '$DATA' -U postgres -A trust --no-sync" >/dev/null
as_server "'$PG_CTL' -D '$DATA' -l '$WORK/server.log' -w \
  -o \"-p $PORT -k '' -c listen_addresses=127.0.0.1 -c fsync=off -c wal_level=logical\" start" >/dev/null \
  || { cat "$WORK/server.log" >&2; exit 1; }

q() { local db="$1"; shift; PGOPTIONS='-c client_min_messages=warning' "$PSQL" -h 127.0.0.1 -p "$PORT" -U postgres -d "$db" -v ON_ERROR_STOP=1 -q -X "$@"; }
scalar() { q "$1" -At -c "$2"; }
copy_db() { q postgres -c "CREATE DATABASE $2 TEMPLATE $1"; }
fail() { echo "go-live-rehearsal: FAILED — $*" >&2; exit 1; }
ok() { echo "go-live-rehearsal: ok — $*"; }

# bundle.sql must be the file the generator produces today.
if ! diff -q <("$ROOT/scripts/ops/bundle-labelos-go-live.sh" | grep -v '^-- Generated by') <(grep -v '^-- Generated by' "$BUNDLE") >/dev/null; then
  fail "supabase/apply/labelos-go-live.sql is stale; rebuild: scripts/ops/bundle-labelos-go-live.sh > supabase/apply/labelos-go-live.sql"
fi
ok "bundle is up to date with its generator"

# 1. production state: everything up to 129, one seeded producer.
q postgres -c "CREATE DATABASE prod_state"
q prod_state -f "$HERE/bootstrap.sql"
for f in "$ROOT"/supabase/migrations/*.sql; do
  n=$((10#$(basename "$f" | cut -c1-3)))
  if [ "$n" -le 129 ]; then q prod_state --single-transaction -f "$f" >/dev/null || fail "migration $(basename "$f")"; fi
done
q prod_state -f "$HERE/seed-production-state.sql"
ok "production state built (001-129 + seeded producer)"

# 2. guard: two producers, and none, both stop the bundle with nothing changed.
for variant in two none; do
  copy_db prod_state "guard_$variant"
  if [ "$variant" = two ]; then
    q "guard_$variant" -c "INSERT INTO public.creator_profiles (user_id, display_name) VALUES ('0b0e1a57-0000-4000-8000-0000000000b1', 'Stray')"
  else
    q "guard_$variant" -c "DELETE FROM public.creator_profiles"
  fi
  if q "guard_$variant" -f "$BUNDLE" >"$WORK/guard.out" 2>&1; then fail "bundle ran with creator_profiles in the '$variant' state"; fi
  grep -q 'go-live stopped' "$WORK/guard.out" || fail "guard message missing ($variant)"
  [ "$(scalar "guard_$variant" "SELECT to_regclass('public.organizations') IS NULL AND to_regclass('public.song_beats') IS NULL")" = t ] \
    || fail "guard ($variant) left something applied"
  ok "guard refuses creator_profiles = $variant and changes nothing"
done

# 3 + 4. the bundle twice, with fingerprints.
copy_db prod_state golive
q golive -f "$HERE/go-live-snapshot.sql" -c "SELECT rehearsal.start()" -c "SELECT rehearsal.take('before')" >/dev/null
rows_expected=$(grep -cE "^  \('[0-9a-z]" "$ROOT/supabase/apply/labelos-verify.sql")
for pass in 1 2; do
  q golive -f "$BUNDLE" >"$WORK/bundle$pass.out" 2>&1 || { tail -20 "$WORK/bundle$pass.out" >&2; fail "bundle run $pass errored"; }
  grep -qiE 'warning|error' "$WORK/bundle$pass.out" && { grep -iE 'warning|error' "$WORK/bundle$pass.out" | head >&2; fail "bundle run $pass printed warnings"; }
  applied=$(grep -c '| applied' "$WORK/bundle$pass.out" || true)
  missing=$(grep -c 'MISSING' "$WORK/bundle$pass.out" || true)
  [ "$missing" = 0 ] && [ "$applied" = "$rows_expected" ] || fail "verify after run $pass: $applied applied, $missing MISSING (expected $rows_expected applied)"
  q golive -c "SELECT rehearsal.take('after$pass')" >/dev/null
  ok "bundle run $pass: no errors, no warnings, $applied/$rows_expected verify rows 'applied'"
done
changed=$(scalar golive "SELECT string_agg(b.tbl, ', ') FROM rehearsal.snap b JOIN rehearsal.snap a ON a.tbl = b.tbl AND a.label IN ('after1', 'after2') WHERE b.label = 'before' AND (a.h <> b.h OR a.n <> b.n)")
[ -z "$changed" ] || fail "existing rows changed in: $changed"
ok "no existing row changed in $(scalar golive "SELECT count(*) FROM rehearsal.cols") tables (incl. auth.users)"
[ "$(scalar golive "SELECT count(*) FROM organizations")" = 1 ] || fail "expected exactly the producer's org"
[ "$(scalar golive "SELECT kind || '/' || role FROM organizations o JOIN org_members m ON m.org_id = o.id WHERE m.user_id = '$PRODUCER'")" = producer/owner ] || fail "producer org / owner membership"
[ "$(scalar golive "SELECT count(*) FROM org_members")" = 1 ] || fail "unexpected org_members rows"
[ "$(scalar golive "SELECT string_agg(user_id::text, ',') FROM platform_admins")" = "$PRODUCER" ] || fail "platform_admins is not exactly the producer"
[ "$(scalar golive "SELECT count(*) FROM activity_events")" = 1 ] || fail "unexpected activity_events rows"
ok "added only: the producer's org + owner membership + org.created + the operator row"

# 5. behaviour checks. They assume the data db:local:check gives them (the
#    seed producer has no org and no contacts), so the rows of the rehearsal
#    are emptied first and seed.sql applied: the SCHEMA under test is the one
#    the production bundle built, the data is the checks' own. (A check is a
#    behaviour proof of the migrations, not of the producer's rows; those were
#    fingerprinted above.)
q golive -c "DROP SCHEMA rehearsal CASCADE"
q golive -At -c "SELECT 'TRUNCATE ' || string_agg(format('public.%I', tablename), ', ') || ' CASCADE' FROM pg_tables WHERE schemaname = 'public'" -o "$WORK/truncate.sql"
q golive -c "SET session_replication_role = replica" -f "$WORK/truncate.sql" -c "TRUNCATE auth.users CASCADE"
q golive -f "$HERE/seed.sql"
n=0
for f in "$ROOT"/supabase/local/checks/*.sql; do
  n=$((n + 1)); copy_db golive "chk_$n"
  q "chk_$n" -o /dev/null -f "$f" || fail "check $(basename "$f")"
done
ok "$n supabase/local/checks passed on the schema the bundle built"

# The migrated production state must have the SAME SCHEMA as a database built
# by applying every migration from nothing (what the local stack and the
# checks use): a diff here means the bundle left production different from
# what the code was tested against.
PGDUMP="$(find_bin pg_dump)"
q postgres -c "CREATE DATABASE fresh"
q fresh -f "$HERE/bootstrap.sql"
for f in "$ROOT"/supabase/migrations/*.sql; do q fresh --single-transaction -f "$f" >/dev/null || fail "fresh build: $(basename "$f")"; done
dump() { "$PGDUMP" -h 127.0.0.1 -p "$PORT" -U postgres -s --no-owner --no-privileges "$1" | grep -vE '^(--|SET |SELECT pg_catalog.set_config|.(un)?restrict )' ; }
dump_priv() { "$PGDUMP" -h 127.0.0.1 -p "$PORT" -U postgres -s --no-owner "$1" | grep -E '^(GRANT|REVOKE|ALTER DEFAULT PRIVILEGES)' | sort; }
if ! diff <(dump golive | sort) <(dump fresh | sort) >"$WORK/schema.diff"; then head -40 "$WORK/schema.diff" >&2; fail "schema differs from a from-scratch build (see above)"; fi
if ! diff <(dump_priv golive) <(dump_priv fresh) >"$WORK/priv.diff"; then head -40 "$WORK/priv.diff" >&2; fail "grants differ from a from-scratch build (see above)"; fi
ok "schema and grants are identical to applying every migration from scratch"
copy_db golive parity
(cd "$ROOT" && npx --no-install jiti scripts/local-db/capability-parity.ts "$WORK/parity.sql") >/dev/null
q parity -f "$WORK/parity.sql" || fail "capability parity"
ok "capability parity — has_org_cap == capabilitiesFor"
echo "go-live-rehearsal: ✓ all passed"
